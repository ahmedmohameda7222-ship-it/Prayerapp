type ValidatableAzkarItem = {
  id: string;
  category: string;
  arabicText: string;
  translationEn: string;
  translationDe: string;
  translationAr: string;
  translationTr: string;
  repeatCount: number;
};

export function validateHardcodedAzkar() {
  const ids = new Set<string>();
  for (const item of hardcodedAzkarItems as readonly ValidatableAzkarItem[]) {
    if (ids.has(item.id)) throw new Error(`Duplicate Azkar id: ${item.id}`);
    ids.add(item.id);
    if (!(hardcodedAzkarCategories as readonly string[]).includes(item.category)) {
      throw new Error(`Invalid Azkar category: ${item.category}`);
    }
    if (!item.arabicText || !item.translationEn || !item.translationDe || !item.translationAr || !item.translationTr) {
      throw new Error(`Missing Azkar text/translation: ${item.id}`);
    }
    if (item.repeatCount <= 0) throw new Error(`Invalid repeatCount: ${item.id}`);
  }
  if (hardcodedAzkarItems.length !== 100) {
    throw new Error(`Expected 100 Azkar items, got ${hardcodedAzkarItems.length}`);
  }
  return true;
}
